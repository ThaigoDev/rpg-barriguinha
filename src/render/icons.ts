const COL: Record<string, string> = { '#': '#1a120a', '+': '#b8823a', 'o': '#f3d9a4' };

export function iconSvg(name: string) {
  const rows = ICONS[name]; if (!rows) return '';
  let r = '';
  rows.forEach((row, y) => { for (let x = 0; x < row.length; x++) { const c = COL[row[x]]; if (c) r += `<rect x="${x}" y="${y}" width="1.02" height="1.02" fill="${c}"/>`; } });
  return `<svg viewBox="0 0 16 16" shape-rendering="crispEdges" width="100%" height="100%">${r}</svg>`;
}

const SPECIAL_ICON: Record<string, string> = { parry: 'parry', dash: 'bolt', slam: 'slam', block: 'shield', cast: 'fire', curse: 'skull' };

/** Coloca ícone + rótulo pequeno em cada botão de toque (atributo data-icon). */
export function applyButtonIcons() {
  document.querySelectorAll<HTMLElement>('.tb[data-icon]').forEach(b => {
    const label = b.dataset.label || '';
    b.innerHTML = `<div class="ic">${iconSvg(b.dataset.icon!)}</div>${label ? `<div class="lb">${label}</div>` : ''}`;
  });
}

/** O botão especial muda de ícone conforme o personagem. */
export function setSpecialIcon(special: string) {
  const b = document.querySelector<HTMLElement>('.tb[data-k="KeyL"]');
  if (!b) return;
  b.dataset.icon = SPECIAL_ICON[special] || 'parry';
  applyButtonIcons();
}
